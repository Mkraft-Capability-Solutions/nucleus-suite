type BreakdownRow = { key: string; label: string; count: number };

type AudienceView = {
  rule: string;
  valid: boolean;
  error: string;
  everyone: boolean;
  resolvedCount: number;
  populationCount: number;
  byDepartment: BreakdownRow[];
  byLocation: BreakdownRow[];
};

type AnnouncementRow = {
  id: string;
  title: string;
  body: string;
  kind: string;
  audienceRule: string;
  audience: AudienceView;
  channels: string[];
  channelsRecorded: boolean;
  createdAt: string;
  publishAt: string;
  publishAtSource: string;
  expiresOn: string | null;
  state: string;
  stateBasis: string;
  stateReason: string;
  acknowledgementRequired: boolean | null;
  autoGenerated: boolean;
  occasionKey: string | null;
  acknowledgedVersion: string | null;
  languages: string[];
  feedReactionCount: number;
  feedCommentCount: number;
  auditTrail: Array<{ action: string; reason: string | null; createdAt: string }>;
  canWrite: boolean;
  populationCount: number;
};

type Vocabulary = { code: string; label: string };
type GapRow = { field: string; workbook: string; reason: string };
type MetricRow = { metric: string; reason: string };
type DimensionRow = { key: string; label: string; available: boolean; note: string };

type Contract = {
  persistedFields: string[];
  unpersistedFields: GapRow[];
  unavailableMetrics: MetricRow[];
  delivery: { transmits: boolean; summary: string; detail: string };
  quietHours: { configured: boolean; detail: string };
  publishAtFallback: { source: string; note: string };
  types: Vocabulary[];
  channels: Vocabulary[];
  languages: Vocabulary[];
  audienceDimensions: DimensionRow[];
};

type Preview = {
  audience: AudienceView;
  refusal: string;
  dimensions: { departments: string[]; locations: string[]; designations: string[]; legalEntities: string[] };
  sample: Array<{ id: string; employeeCode: string; name: string; department: string | null; location: string | null }>;
  contract: Contract | null;
};

function readBreakdown(value: unknown): BreakdownRow[] {
  return (Array.isArray(value) ? (value as UnknownRecord[]) : []).map((entry) => ({
    key: str(entry.key, "—"),
    label: str(entry.label, str(entry.key, "—")),
    count: int(entry.count),
  }));
}

function readAudience(value: unknown): AudienceView {
  const record = asRecord(value);
  return {
    rule: str(record.rule),
    valid: record.valid === true,
    error: str(record.error),
    everyone: record.everyone === true,
    resolvedCount: int(record.resolvedCount),
    populationCount: int(record.populationCount),
    byDepartment: readBreakdown(record.byDepartment),
    byLocation: readBreakdown(record.byLocation),
  };
}

function readVocabulary(value: unknown): Vocabulary[] {
  return (Array.isArray(value) ? (value as UnknownRecord[]) : []).map((entry) => ({ code: str(entry.code), label: str(entry.label, str(entry.code)) }));
}

function readContract(value: unknown): Contract | null {
  const record = asRecord(value);
  if (Object.keys(record).length === 0) return null;
  const delivery = asRecord(record.delivery);
  const quietHours = asRecord(record.quietHours);
  const fallback = asRecord(record.publishAtFallback);
  return {
    persistedFields: strList(record.persistedFields),
    unpersistedFields: (Array.isArray(record.unpersistedFields) ? (record.unpersistedFields as UnknownRecord[]) : []).map((entry) => ({
      field: str(entry.field),
      workbook: str(entry.workbook),
      reason: str(entry.reason),
    })),
    unavailableMetrics: (Array.isArray(record.unavailableMetrics) ? (record.unavailableMetrics as UnknownRecord[]) : []).map((entry) => ({
      metric: str(entry.metric),
      reason: str(entry.reason),
    })),
    delivery: { transmits: delivery.transmits === true, summary: str(delivery.summary), detail: str(delivery.detail) },
    quietHours: { configured: quietHours.configured === true, detail: str(quietHours.detail) },
    publishAtFallback: { source: str(fallback.source), note: str(fallback.note) },
    types: readVocabulary(record.types),
    channels: readVocabulary(record.channels),
    languages: readVocabulary(record.languages),
    audienceDimensions: (Array.isArray(record.audienceDimensions) ? (record.audienceDimensions as UnknownRecord[]) : []).map((entry) => ({
      key: str(entry.key),
      label: str(entry.label, str(entry.key)),
      available: entry.available === true,
      note: str(entry.note),
    })),
  };
}

function readRows(payload: unknown): AnnouncementRow[] {
  const data = asRecord(payload).data;
  return (Array.isArray(data) ? (data as UnknownRecord[]) : []).map((item) => ({
    id: str(item.id),
    title: str(item.title, "Untitled announcement"),
    body: str(item.body),
    kind: str(item.kind, "—"),
    audienceRule: str(item.audienceRule, "all"),
    audience: readAudience(item.audience),
    channels: strList(item.channels),
    channelsRecorded: item.channelsRecorded === true,
    createdAt: str(item.createdAt),
    publishAt: str(item.publishAt),
    publishAtSource: str(item.publishAtSource),
    expiresOn: typeof item.expiresOn === "string" ? item.expiresOn : null,
    state: str(item.state, "published"),
    stateBasis: str(item.stateBasis),
    stateReason: str(item.stateReason),
    acknowledgementRequired: typeof item.acknowledgementRequired === "boolean" ? item.acknowledgementRequired : null,
    autoGenerated: item.autoGenerated === true,
    occasionKey: typeof item.occasionKey === "string" ? item.occasionKey : null,
    acknowledgedVersion: typeof item.acknowledgedVersion === "string" ? item.acknowledgedVersion : null,
    languages: strList(item.languages),
    feedReactionCount: int(item.feedReactionCount),
    feedCommentCount: int(item.feedCommentCount),
    auditTrail: (Array.isArray(item.auditTrail) ? (item.auditTrail as UnknownRecord[]) : []).map((entry) => ({
      action: str(entry.action, "—"),
      reason: typeof entry.reason === "string" ? entry.reason : null,
      createdAt: str(entry.createdAt),
    })),
    canWrite: item.canWrite === true,
    populationCount: int(item.populationCount),
  }));
}

function readPreview(payload: unknown): Preview {
  const data = asRecord(asRecord(payload).data);
  const dimensions = asRecord(data.dimensions);
  return {
    audience: readAudience(data),
    refusal: str(data.refusal),
    dimensions: {
      departments: strList(dimensions.departments),
      locations: strList(dimensions.locations),
      designations: strList(dimensions.designations),
      legalEntities: strList(dimensions.legalEntities),
    },
    sample: (Array.isArray(data.sample) ? (data.sample as UnknownRecord[]) : []).map((entry) => ({
      id: str(entry.id),
      employeeCode: str(entry.employeeCode),
      name: str(entry.name),
      department: typeof entry.department === "string" ? entry.department : null,
      location: typeof entry.location === "string" ? entry.location : null,
    })),
    contract: readContract(data.contract),
  };
}

