type UnknownRecord = Record<string, unknown>;

function asRecord(value: unknown): UnknownRecord {
  return typeof value === "object" && value !== null ? (value as UnknownRecord) : {};
}

function str(value: unknown, fallback = ""): string {
  return typeof value === "string" ? value : fallback;
}

function int(value: unknown): number {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? Math.trunc(parsed) : 0;
}

function strList(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((entry): entry is string => typeof entry === "string") : [];
}

/** The announcement's real state, as the register derives it. */
function statusTone(state: string): "success" | "warning" | "danger" | "info" | "neutral" {
  if (state === "published") return "success";
  if (state === "scheduled") return "info";
  if (state === "archived") return "warning";
  if (state === "draft") return "neutral";
  return "neutral";
}

function stateLabel(state: string): string {
  if (state === "draft") return "Draft";
  if (state === "scheduled") return "Scheduled";
  if (state === "published") return "Published";
  if (state === "archived") return "Archived";
  return state || "—";
}

function basisLabel(basis: string): string {
  if (basis === "stored") return "from a stored state";
  if (basis === "expiry") return "derived from the expiry date";
  if (basis === "publish_at") return "derived from publish-at";
  return basis || "—";
}

function timestamp(value: string): string {
  if (!value) return "—";
  const parsed = Date.parse(value);
  return Number.isFinite(parsed) ? new Date(parsed).toISOString().replace("T", " ").slice(0, 16) : value;
}

