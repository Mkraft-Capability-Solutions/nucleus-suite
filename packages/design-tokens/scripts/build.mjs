/**
 * Build @nucleus/design-tokens from src/tokens.ts:
 *   dist/tokens.css   CSS custom properties (scales on :root; colours per [data-theme][data-mode], system mode via
 *                     prefers-color-scheme, reduced motion zeroes durations)
 *   dist/themes.json  every theme × mode as OKLCH + hex, plus the scales (API tenant settings, React Native)
 *   dist/index.js     typed runtime exports (theme ids, metadata, swatches, token names, scales)
 *   dist/index.d.ts   their types
 * The WCAG contrast gate runs first; any failing pair fails the build.
 */
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { checkContrast } from './check-contrast.mjs';
import {
  APPROVED_THEME_IDS,
  BREAKPOINT,
  COLOR_TOKEN_NAMES,
  CONTROL,
  DEFAULT_MODE_PREFERENCE,
  DEFAULT_THEME_ID,
  DURATION,
  EASING,
  FONT_FAMILY,
  FONT_SIZE,
  FONT_SIZE_PX,
  FONT_WEIGHT,
  LAYOUT,
  LETTER_SPACING,
  LINE_HEIGHT,
  MODE_PREFERENCES,
  RADIUS,
  SHADOW,
  SPACE,
  THEME_IDS,
  THEME_MODES,
  Z_INDEX,
  resolveThemes,
  toCss,
  toHex,
} from '../src/tokens.ts';

const DIST = fileURLToPath(new URL('../dist/', import.meta.url));
const HEADER = '/* Generated by @nucleus/design-tokens scripts/build.mjs. Do not edit; change src/ and rebuild. */';

const px = (value) => (value === 0 ? '0' : `${value}px`);

/** Theme-independent custom properties: [name, value]. */
function scaleProperties() {
  return [
    ...Object.entries(SPACE).map(([key, value]) => [`space-${key}`, px(value)]),
    ...Object.entries(RADIUS).map(([key, value]) => [`radius-${key}`, px(value)]),
    ...Object.entries(FONT_SIZE).map(([key, value]) => [`font-size-${key}`, value]),
    ...Object.entries(FONT_WEIGHT).map(([key, value]) => [`font-weight-${key}`, String(value)]),
    ...Object.entries(LINE_HEIGHT).map(([key, value]) => [`line-height-${key}`, String(value)]),
    ...Object.entries(LETTER_SPACING).map(([key, value]) => [`letter-spacing-${key}`, value]),
    ...Object.entries(SHADOW).map(([key, value]) => [`shadow-${key}`, value]),
    ...Object.entries(Z_INDEX).map(([key, value]) => [`z-${key}`, String(value)]),
    ...Object.entries(DURATION).map(([key, value]) => [`duration-${key}`, `${value}ms`]),
    ...Object.entries(EASING).map(([key, value]) => [`ease-${key}`, value]),
    ...Object.entries(BREAKPOINT).map(([key, value]) => [`breakpoint-${key}`, px(value)]),
    ...Object.entries(LAYOUT).map(([key, value]) => [`layout-${key}`, value]),
    ...Object.entries(CONTROL).map(([key, value]) => [`control-${key}`, px(value)]),
  ];
}

function block(selector, properties, indent = '') {
  const body = properties.map(([name, value]) => `${indent}  --${name}: ${value};`).join('\n');
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

function colorProperties(colors) {
  return COLOR_TOKEN_NAMES.map((name) => [`color-${name}`, toCss(colors[name])]);
}

function withScheme(css, mode) {
  return css.replace(/\n(\s*)}$/, `\n$1  color-scheme: ${mode};\n$1}`);
}

function buildCss(themes) {
  const fallback = themes.find((theme) => theme.spec.id === DEFAULT_THEME_ID);
  const swatches = themes.map((theme) => [
    `theme-swatch-${theme.spec.id}`,
    `light-dark(${toCss(theme.colors.light['accent-default'])}, ${toCss(theme.colors.dark['accent-default'])})`,
  ]);
  const fontStacks = Object.entries(FONT_FAMILY).map(([key, value]) => [`font-${key}`, value]);
  const parts = [HEADER, '', block(':root', scaleProperties()), ''];
  parts.push('/* Font stacks re-resolve on any element marked data-font-scope, so faces set on that element (e.g. a');
  parts.push('   route-scoped preloaded display face) take effect inside it. */');
  parts.push(block(':root,\n[data-font-scope]', fontStacks), '');
  parts.push('/* Accent of every theme in the active mode, for theme pickers that preview other themes. */');
  parts.push(block(':root', swatches), '');
  parts.push('/* Default theme when <html> has no data-theme (or an unknown one). */');
  parts.push(withScheme(block(':root', colorProperties(fallback.colors.light)), 'light'));
  parts.push(withScheme(block(':root[data-mode="dark"]', colorProperties(fallback.colors.dark)), 'dark'));
  parts.push(`@media (prefers-color-scheme: dark) {\n${withScheme(block(':root:not([data-mode="light"])', colorProperties(fallback.colors.dark), '  '), 'dark')}\n}`);
  for (const theme of themes) {
    const id = theme.spec.id;
    parts.push('', `/* ${theme.spec.displayName}: ${theme.spec.description} */`);
    parts.push(withScheme(block(`:root[data-theme="${id}"]`, colorProperties(theme.colors.light)), 'light'));
    parts.push(withScheme(block(`:root[data-theme="${id}"][data-mode="dark"]`, colorProperties(theme.colors.dark)), 'dark'));
    parts.push(`@media (prefers-color-scheme: dark) {\n${withScheme(block(`:root[data-theme="${id}"]:not([data-mode="light"])`, colorProperties(theme.colors.dark), '  '), 'dark')}\n}`);
  }
  const durations = Object.keys(DURATION).map((key) => [`duration-${key}`, '0ms']);
  parts.push('', '/* Reduced motion: every token-driven transition becomes instant. */');
  parts.push(`@media (prefers-reduced-motion: reduce) {\n${block(':root', durations, '  ')}\n}`);
  return `${parts.join('\n')}\n`;
}

function swatch(colors) {
  return {
    accent: toHex(colors['accent-default']),
    onAccent: toHex(colors['text-on-accent']),
    accentText: toHex(colors['accent-text']),
    surface: toHex(colors.surface),
    bg: toHex(colors.bg),
    text: toHex(colors['text-primary']),
  };
}

function themeMetadata(themes) {
  return themes.map((theme) => ({
    id: theme.spec.id,
    displayName: theme.spec.displayName,
    description: theme.spec.description,
    swatch: { light: swatch(theme.colors.light), dark: swatch(theme.colors.dark) },
  }));
}

function buildJson(themes) {
  const modeColors = (colors) =>
    Object.fromEntries(COLOR_TOKEN_NAMES.map((name) => [name, { oklch: toCss(colors[name]), hex: toHex(colors[name]) }]));
  return {
    version: 1,
    defaultThemeId: DEFAULT_THEME_ID,
    defaultModePreference: DEFAULT_MODE_PREFERENCE,
    themeIds: THEME_IDS,
    approvedThemeIds: APPROVED_THEME_IDS,
    modes: THEME_MODES,
    themes: themes.map((theme) => ({
      id: theme.spec.id,
      displayName: theme.spec.displayName,
      description: theme.spec.description,
      light: modeColors(theme.colors.light),
      dark: modeColors(theme.colors.dark),
    })),
    scales: {
      space: SPACE,
      radius: RADIUS,
      fontFamily: FONT_FAMILY,
      fontSize: FONT_SIZE,
      fontSizePx: FONT_SIZE_PX,
      fontWeight: FONT_WEIGHT,
      lineHeight: LINE_HEIGHT,
      letterSpacing: LETTER_SPACING,
      zIndex: Z_INDEX,
      duration: DURATION,
      easing: EASING,
      breakpoint: BREAKPOINT,
      layout: LAYOUT,
      control: CONTROL,
    },
  };
}

function buildIndexJs(themes) {
  const tokenNames = [...COLOR_TOKEN_NAMES.map((name) => `color-${name}`), ...THEME_IDS.map((id) => `theme-swatch-${id}`), ...Object.keys(FONT_FAMILY).map((key) => `font-${key}`), ...scaleProperties().map(([name]) => name)];
  const json = (value) => JSON.stringify(value, null, 2);
  return `${HEADER.replace('/*', '//').replace(' */', '')}
export const THEME_IDS = Object.freeze(${json(THEME_IDS)});
export const APPROVED_THEME_IDS = Object.freeze(${json(APPROVED_THEME_IDS)});
export const MODE_PREFERENCES = Object.freeze(${json(MODE_PREFERENCES)});
export const THEME_MODES = Object.freeze(${json(THEME_MODES)});
export const DEFAULT_THEME_ID = ${json(DEFAULT_THEME_ID)};
export const DEFAULT_MODE_PREFERENCE = ${json(DEFAULT_MODE_PREFERENCE)};
export const THEMES = Object.freeze(${json(themeMetadata(themes))});
export const COLOR_TOKEN_NAMES = Object.freeze(${json(COLOR_TOKEN_NAMES)});
export const TOKEN_NAMES = Object.freeze(${json(tokenNames)});
export const BREAKPOINT = Object.freeze(${json(BREAKPOINT)});
export const DURATION = Object.freeze(${json(DURATION)});
export const Z_INDEX = Object.freeze(${json(Z_INDEX)});

/** Whether a value is a known theme id. */
export function isThemeId(value) {
  return typeof value === 'string' && THEME_IDS.includes(value);
}

/** Whether a value is a theme viewers may pick (approved). */
export function isApprovedThemeId(value) {
  return typeof value === 'string' && APPROVED_THEME_IDS.includes(value);
}

/** Whether a value is a known mode preference (light | dark | system). */
export function isModePreference(value) {
  return typeof value === 'string' && MODE_PREFERENCES.includes(value);
}

/** CSS var() reference for a token name, e.g. cssVar('color-surface') → 'var(--color-surface)'. */
export function cssVar(name) {
  return \`var(--\${name})\`;
}
`;
}

function buildIndexDts() {
  const union = (values) => values.map((value) => JSON.stringify(value)).join(' | ');
  const tokenNames = [...COLOR_TOKEN_NAMES.map((name) => `color-${name}`), ...THEME_IDS.map((id) => `theme-swatch-${id}`), ...Object.keys(FONT_FAMILY).map((key) => `font-${key}`), ...scaleProperties().map(([name]) => name)];
  return `${HEADER.replace('/*', '//').replace(' */', '')}
export type ThemeId = ${union(THEME_IDS)};
export type ThemeMode = ${union(THEME_MODES)};
export type ModePreference = ${union(MODE_PREFERENCES)};
export type ColorTokenName = ${union(COLOR_TOKEN_NAMES)};
export type TokenName = ${union(tokenNames)};

export interface ThemeSwatch {
  readonly accent: string;
  readonly onAccent: string;
  readonly accentText: string;
  readonly surface: string;
  readonly bg: string;
  readonly text: string;
}

export interface ThemeMetadata {
  readonly id: ThemeId;
  readonly displayName: string;
  readonly description: string;
  readonly swatch: Readonly<Record<ThemeMode, ThemeSwatch>>;
}

export declare const THEME_IDS: readonly ThemeId[];
/** Themes offered in theme pickers (approved by the product owner). */
export declare const APPROVED_THEME_IDS: readonly ThemeId[];
export declare const MODE_PREFERENCES: readonly ModePreference[];
export declare const THEME_MODES: readonly ThemeMode[];
export declare const DEFAULT_THEME_ID: ThemeId;
export declare const DEFAULT_MODE_PREFERENCE: ModePreference;
export declare const THEMES: readonly ThemeMetadata[];
export declare const COLOR_TOKEN_NAMES: readonly ColorTokenName[];
export declare const TOKEN_NAMES: readonly TokenName[];
export declare const BREAKPOINT: Readonly<Record<${union(Object.keys(BREAKPOINT))}, number>>;
export declare const DURATION: Readonly<Record<${union(Object.keys(DURATION))}, number>>;
export declare const Z_INDEX: Readonly<Record<${union(Object.keys(Z_INDEX))}, number>>;
export declare function isThemeId(value: unknown): value is ThemeId;
export declare function isApprovedThemeId(value: unknown): value is ThemeId;
export declare function isModePreference(value: unknown): value is ModePreference;
export declare function cssVar(name: TokenName): string;
`;
}

async function main() {
  if (checkContrast() !== 0) {
    console.error('\nBuild failed: contrast requirements not met.');
    return 1;
  }
  const themes = resolveThemes();
  await rm(DIST, { recursive: true, force: true });
  await mkdir(DIST, { recursive: true });
  await Promise.all([
    writeFile(`${DIST}tokens.css`, buildCss(themes)),
    writeFile(`${DIST}themes.json`, `${JSON.stringify(buildJson(themes), null, 2)}\n`),
    writeFile(`${DIST}index.js`, buildIndexJs(themes)),
    writeFile(`${DIST}index.d.ts`, buildIndexDts()),
  ]);
  console.log(`\nBuilt dist/tokens.css, dist/themes.json, dist/index.js, dist/index.d.ts (${themes.length} themes × 2 modes).`);
  return 0;
}

process.exitCode = await main();
