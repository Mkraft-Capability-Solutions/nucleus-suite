import { readdir, readFile, writeFile } from 'node:fs/promises';
const files = (await readdir(new URL('../src/config/ui/', import.meta.url))).filter((name) => name.endsWith('.json')).sort();
const imports = files.map((name, index) => `import resource${index} from "./ui/${name}";`);
const entries = files.map((name, index) => `    ${JSON.stringify(name.slice(0, -5))}: resource${index},`);
await writeFile(new URL('../src/config/workspace-manifest.ts', import.meta.url), `// Generated by npm run data:manifest. JSON imports remain server-side.\nimport "server-only";\nimport workbook from "./workbook.json";\n${imports.join('\n')}\n\nexport const workspaceResources = {\n    workbook,\n${entries.join('\n')}\n};\n`);

const contract = {};
for (const file of files) {
    contract[file.slice(0, -5)] = Object.keys(JSON.parse(await readFile(new URL('../src/config/ui/' + file, import.meta.url), 'utf8')));
}
contract.workbook = ['sheets'];
await writeFile(new URL('../src/config/workspace-contract.mjs', import.meta.url), '// Generated resource/field names only; contains no fixture values.\nexport const workspaceContract = ' + JSON.stringify(contract, null, 2) + ';\n');
